/**
 * Phishing Website Detector - Frontend JavaScript Engine
 * Manages AJAX API interactions, URL feature rendering, and Chart.js analytics.
 */

let metricsChart = null;

document.addEventListener('DOMContentLoaded', () => {
    // Load initial ML metrics on startup
    loadMetrics();
});

/**
 * Fills sample URL into input box for quick testing.
 */
function fillPreset(url) {
    const input = document.getElementById('urlInput');
    input.value = url;
    // Trigger submission
    document.getElementById('urlForm').dispatchEvent(new Event('submit', { cancelable: true }));
}

/**
 * Submits URL to Flask backend API for local ML analysis.
 */
async function analyzeUrl(event) {
    event.preventDefault();

    const urlInput = document.getElementById('urlInput');
    const rawUrl = urlInput.value.trim();

    if (!rawUrl) {
        alert("Please enter a valid website URL.");
        return;
    }

    const btnText = document.getElementById('btnText');
    const btnSpinner = document.getElementById('btnSpinner');
    const analyzeBtn = document.getElementById('analyzeBtn');

    // Set UI Loading State
    btnText.innerHTML = '<i class="fas fa-spinner fa-spin"></i> Analyzing...';
    btnSpinner.classList.remove('hidden');
    analyzeBtn.disabled = true;

    try {
        const response = await fetch('/predict', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ url: rawUrl })
        });

        const data = await response.json();

        if (response.ok && data.status === 'success') {
            displayResults(data);
        } else {
            alert(data.message || "Failed to analyze URL. Please check input.");
        }
    } catch (err) {
        console.error("Error analyzing URL:", err);
        alert("Backend server error. Ensure Flask app is running.");
    } finally {
        // Reset UI Loading State
        btnText.innerHTML = '<i class="fas fa-shield-virus"></i> Analyze URL';
        btnSpinner.classList.add('hidden');
        analyzeBtn.disabled = false;
    }
}

/**
 * Renders prediction badge, confidence score, and feature list.
 */
function displayResults(data) {
    const resultCard = document.getElementById('resultCard');
    const featuresSection = document.getElementById('featuresSection');
    const predictionBadge = document.getElementById('predictionBadge');
    const confidenceText = document.getElementById('confidenceText');
    const progressCircle = document.getElementById('progressCircle');
    const explanationText = document.getElementById('explanationText');
    const timestampBadge = document.getElementById('timestampBadge');
    const featuresGrid = document.getElementById('featuresGrid');

    // Reveal Cards
    resultCard.classList.remove('hidden');
    featuresSection.classList.remove('hidden');

    // Set Timestamp
    timestampBadge.textContent = new Date().toLocaleTimeString();

    // 1. Render Status Badge
    if (data.prediction_code === 1) {
        predictionBadge.className = 'prediction-badge badge-phishing';
        predictionBadge.innerHTML = '<i class="fas fa-triangle-exclamation"></i> PHISHING';
    } else {
        predictionBadge.className = 'prediction-badge badge-legitimate';
        predictionBadge.innerHTML = '<i class="fas fa-shield-check"></i> LEGITIMATE';
    }

    // 2. Render Confidence Score Radial Ring
    confidenceText.textContent = `${data.confidence}%`;
    const circumference = 251.2; // 2 * pi * r (r=40)
    const offset = circumference - (data.confidence / 100) * circumference;
    progressCircle.style.strokeDashoffset = offset;
    progressCircle.style.stroke = data.prediction_code === 1 ? '#ef4444' : '#10b981';

    // 3. Render Explanation
    explanationText.textContent = data.explanation;

    // 4. Render Extracted Features Grid
    featuresGrid.innerHTML = '';
    const features = data.features || {};

    for (const [key, val] of Object.entries(features)) {
        const item = document.createElement('div');
        item.className = 'feature-item';

        let icon = '<i class="fas fa-angle-right text-cyan"></i>';
        if (val === 'Detected' || val === 'Detected (HTTP)') icon = '<i class="fas fa-circle-exclamation text-danger"></i>';
        if (val === 'Detected (Secure)') icon = '<i class="fas fa-shield-halved text-success"></i>';

        item.innerHTML = `
            <span class="feature-key">${icon} ${key}</span>
            <span class="feature-val">${val}</span>
        `;
        featuresGrid.appendChild(item);
    }

    // Scroll smoothly to results
    resultCard.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
}

/**
 * Loads training evaluation metrics generated by train_model.py.
 */
async function loadMetrics() {
    try {
        const response = await fetch('/api/metrics');
        const jsonRes = await response.json();

        if (response.ok && jsonRes.status === 'success') {
            const metrics = jsonRes.data;
            renderChart(metrics.models);
            renderConfusionMatrix(metrics.models, metrics.best_model);
            
            const bestBadge = document.getElementById('bestModelBadge');
            if (bestBadge) bestBadge.textContent = `Best Model: ${metrics.best_model}`;
        }
    } catch (err) {
        console.warn("Unable to fetch model metrics:", err);
    }
}

/**
 * Builds interactive comparative bar chart using Chart.js.
 */
function renderChart(modelsData) {
    const ctx = document.getElementById('metricsChart').getContext('2d');
    const modelNames = Object.keys(modelsData);

    const accuracies = modelNames.map(m => modelsData[m].accuracy);
    const precisions = modelNames.map(m => modelsData[m].precision);
    const recalls = modelNames.map(m => modelsData[m].recall);
    const f1s = modelNames.map(m => modelsData[m].f1_score);

    if (metricsChart) {
        metricsChart.destroy();
    }

    metricsChart = new Chart(ctx, {
        type: 'bar',
        data: {
            labels: modelNames,
            datasets: [
                {
                    label: 'Accuracy (%)',
                    data: accuracies,
                    backgroundColor: 'rgba(0, 242, 254, 0.7)',
                    borderColor: '#00f2fe',
                    borderWidth: 1
                },
                {
                    label: 'Precision (%)',
                    data: precisions,
                    backgroundColor: 'rgba(59, 130, 246, 0.7)',
                    borderColor: '#3b82f6',
                    borderWidth: 1
                },
                {
                    label: 'Recall (%)',
                    data: recalls,
                    backgroundColor: 'rgba(245, 158, 11, 0.7)',
                    borderColor: '#f59e0b',
                    borderWidth: 1
                },
                {
                    label: 'F1-Score (%)',
                    data: f1s,
                    backgroundColor: 'rgba(16, 185, 129, 0.7)',
                    borderColor: '#10b981',
                    borderWidth: 1
                }
            ]
        },
        options: {
            responsive: true,
            maintainAspectRatio: false,
            scales: {
                y: {
                    beginAtZero: true,
                    max: 100,
                    grid: { color: 'rgba(255, 255, 255, 0.05)' },
                    ticks: { color: '#94a3b8' }
                },
                x: {
                    grid: { display: false },
                    ticks: { color: '#94a3b8' }
                }
            },
            plugins: {
                legend: {
                    labels: { color: '#f8fafc', font: { family: 'Outfit' } }
                }
            }
        }
    });
}

/**
 * Renders the confusion matrix grid values for the selected model.
 */
function renderConfusionMatrix(modelsData, bestModelName) {
    const activeModelName = document.getElementById('activeModelName');
    if (activeModelName) activeModelName.textContent = bestModelName;

    const targetModel = modelsData[bestModelName] || Object.values(modelsData)[0];
    if (!targetModel || !targetModel.confusion_matrix) return;

    const [[tn, fp], [fn, tp]] = targetModel.confusion_matrix;

    document.getElementById('cmTN').textContent = tn;
    document.getElementById('cmFP').textContent = fp;
    document.getElementById('cmFN').textContent = fn;
    document.getElementById('cmTP').textContent = tp;
}
